#!/usr/bin/env python3
"""Conservative public-release gate for this specific portfolio repository.
Checks staged/tracked and present repository files. Not legal or image-content review.
"""
from pathlib import Path
import re,sys,csv,hashlib
ROOT=Path(__file__).resolve().parents[1]
BLOCKED={'.db','.lib','.lef','.tf','.gds','.gdsii','.def','.ddc','.svf','.spef','.spf','.sdf','.vcd','.fsdb','.wlf','.vpd','.saif','.enc','.rpt','.tarpt','.log','.ctstch','.slk','.fp','.spr','.gz','.map','.capTbl','.summary','.sdc','.zip','.7z','.lic','.key','.pem'}
TEXT={'.v','.sv','.tcl','.do','.sh','.sdc','.prj','.txt','.conf','.json','.yaml','.yml','.xml','.md','.csv'}
private_pattern=re.compile(r'/(?:home|Users|mnt|opt/eda|eda|foundry|private)/[^\s\"\']+',re.I)
markers=re.compile(r'(?i)copyright\s*\(?c\)?\s*\d{4}.*(?:synopsys|cadence|mentor|siemens)|this software (?:and the associated documentation )?is proprietary|distribution of this software is strictly prohibited')
REPORT_MANIFEST=ROOT/'reports'/'TOOL_REPORT_PROVENANCE.csv'
REPORT_ALLOWED={}
if REPORT_MANIFEST.exists():
 with REPORT_MANIFEST.open(encoding='utf8',newline='') as fp:
  for entry in csv.DictReader(fp):REPORT_ALLOWED[entry['public_path']]=entry['published_sha256']
INTERNAL_FILES = {
    "linkedin_post.md", "publication_checklist.md", "publishing_guide.md",
}
issues=[]; checked=0
for p in ROOT.rglob('*'):
 if not p.is_file():continue
 rel=p.relative_to(ROOT);rs=str(rel).replace('\\','/')
 if any(x in rel.parts for x in ['.git','__pycache__']):continue
 checked+=1
 if p.name.lower() in INTERNAL_FILES:
  issues.append((rs,'internal publication document'))
 if rs.startswith('reports/tool_exports/') and rs not in REPORT_ALLOWED:
  issues.append((rs,'EDA export without a reviewed manifest entry'))
 if (p.suffix.lower() in {e.lower() for e in BLOCKED} and rs not in REPORT_ALLOWED) or p.name.endswith('~'):
  issues.append((rs,'restricted/generated extension'))
 if rs in REPORT_ALLOWED:
  if hashlib.sha256(p.read_bytes()).hexdigest()!=REPORT_ALLOWED[rs]:issues.append((rs,'original report changed or corrupted since review'))
 if any(x.lower() in {'std_cells','pdk','foundry','formality_svf','export','private','netlists','mapped_netlists','ddc'} for x in rel.parts) or p.name.endswith('_pg.v'):
  issues.append((rs,'restricted directory'))
 if p.suffix.lower() in TEXT or rs in REPORT_ALLOWED:
  data=p.read_text(encoding='utf8',errors='replace')
  # Do not scan checker itself or legal documentation for example patterns.
  if p!=Path(__file__).resolve() and private_pattern.search(data):issues.append((rs,'absolute local/private path'))
  if p!=Path(__file__).resolve() and markers.search(data):issues.append((rs,'vendor proprietary/copyright boilerplate'))
  if p.suffix.lower() in {'.v','.sdc','.tcl'} and re.search(r'(?im)\b(?:created by: synopsys|generated by:.*cadence|cadence first encounter|dc expert\(tm\) in wire load mode|synopsys dc expert\(tm\))\b',data):
   issues.append((rs,'auto-generated EDA script/netlist header: require manual review'))
 if p.suffix.lower() in {'.png','.jpg','.jpeg','.webp'}:
  try:
   from PIL import Image
   with Image.open(p) as im:
    meta=' '.join(str(k)+' '+str(v) for k,v in im.info.items())
    if private_pattern.search(meta) or markers.search(meta):issues.append((rs,'possible sensitive image metadata'))
  except ImportError:
   pass # no Pillow: user must inspect image metadata manually
  except Exception as e:issues.append((rs,f'image metadata check failed: {e}'))
for rp in REPORT_ALLOWED:
 if not (ROOT/rp).exists():issues.append((rp,'provenance report missing'))
print(f'Checked {checked} files including {len(REPORT_ALLOWED)} approved tool reports; image pixels and ownership need HUMAN review.')
if issues:
 for f,why in issues:print(f'BLOCK: {f}: {why}')
 print('RELEASE CHECK FAILED');sys.exit(1)
print('AUTOMATED FILE-TYPE/PATH CHECK PASSED (NOT LICENSE CLEARANCE)')
